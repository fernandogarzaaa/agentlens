"""Collect results/*.json into results/SUMMARY.md (the tables quoted in the README)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROWS = [
    ("n_cases", "Cases", "{:.0f}"),
    ("task_success", "Task success", "{:.1%}"),
    ("tool_f1", "Tool F1 (macro)", "{:.3f}"),
    ("tool_precision", "Tool precision", "{:.3f}"),
    ("tool_recall", "Tool recall", "{:.3f}"),
    ("args_exact", "Args exact", "{:.1%}"),
    ("args_partial", "Args partial", "{:.1%}"),
    ("trajectory_match", "Trajectory match", "{:.1%}"),
    ("constraint_pass", "Constraints pass", "{:.1%}"),
    ("answer_pass", "Answer checks pass", "{:.1%}"),
    ("error_rate", "Error rate", "{:.1%}"),
    ("avg_steps", "Steps / task", "{:.2f}"),
    ("avg_tokens", "Tokens / task", "{:.0f}"),
    ("cost_per_task_usd", "$ / task", "${:.4f}"),
    ("latency_p50_s", "Latency p50 (s)", "{:.1f}"),
    ("latency_p95_s", "Latency p95 (s)", "{:.1f}"),
]


def main(results_dir: str = "results") -> None:
    d = Path(results_dir)
    evals = {}
    for p in sorted(d.glob("*.json")):
        data = json.loads(p.read_text())
        if "summary" in data and "cases" in data:
            evals[p.stem] = data
    lines = [
        "# Measured results",
        "",
        "Generated by `scripts/summarize_results.py` from the JSON files in this folder.",
        "",
    ]
    if evals:
        names = list(evals)
        lines += ["| Metric | " + " | ".join(f"`{n}`" for n in names) + " |", "|---|" + "---|" * len(names)]
        for key, label, fmt in ROWS:
            cells = []
            for n in names:
                v = evals[n]["summary"].get(key)
                cells.append("-" if v is None else fmt.format(v))
            lines.append(f"| {label} | " + " | ".join(cells) + " |")
        lines.append("")
        for n in names:
            e = evals[n]
            meta = f", {json.dumps(e['metadata'])}" if e.get("metadata") else ""
            lines.append(
                f"- `{n}`: suite `{e['suite']}`, agent `{e['agent']}`, model `{e['model']}`, created {e['created']}{meta}"
            )
    for p in sorted(d.glob("judge_*.json")):
        rep = json.loads(p.read_text())
        if "kappa" not in rep:
            continue
        lines += [
            "",
            f"## Judge calibration: `{p.stem}`",
            "",
            f"n = {rep['n']}, accuracy = {rep['accuracy']:.3f}, Cohen's kappa = {rep['kappa']:.3f}, abstentions = {rep['abstentions']}",
            "",
            f"Human label distribution: {rep['human_distribution']}; judge: {rep['judge_distribution']}",
            "",
            "Confusion (rows = human, columns = judge):",
            "",
            "| human \\ judge | " + " | ".join(rep["labels"]) + " |",
            "|---|" + "---|" * len(rep["labels"]),
        ]
        for t in rep["labels"]:
            row = rep["confusion"].get(t, {})
            lines.append(f"| {t} | " + " | ".join(str(row.get(x, 0)) for x in rep["labels"]) + " |")
        if rep.get("metadata"):
            lines += ["", f"Metadata: `{json.dumps(rep['metadata'])}`"]
    (d / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print((d / "SUMMARY.md").read_text())


if __name__ == "__main__":
    main(*sys.argv[1:])
